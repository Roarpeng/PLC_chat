"""Real V19 compile for the ProcessOS clamp slice on a pre-fabricated skeleton.

PLAN §5 flow: "Open known project COPY / baseline skeleton" — this machine's
TIA device catalog lacks the default CPU type id, so we reuse the proven G5
skeleton (tmp_validate/g5_skeleton_20261112_210500/proj/CanvasE2E.ap19, the
project COPY behind evidence/v2/real/attempt_04) instead of CREATE_DEVICE.

Steps: copy skeleton -> build processos manifest (FB->DB->OB) -> delegate to
scripts/skeleton_delivery_v2.py --real IN-PROCESS via runpy (no subprocess,
no shell — argv elements are resolved Path strings and fixed literals), i.e.
open/import/compile/save/archive/hash/retrieve-reopen with every stage from
persisted receipts (P-14 discipline).
Honesty: only a real 0-error compile + archive + reopen yields V19_real; the
skeleton's pre-existing G5 blocks stay in the copy (recorded here, never
claimed as generated by processos).
"""
from __future__ import annotations

import runpy
import shutil
import sys
from pathlib import Path
from typing import Any

REPO = Path(__file__).resolve().parents[1]
# Default skeleton = the PRISTINE baseline (evidence/v2/real/
# canvas_baseline_compile.txt: empty CanvasE2E compiled 0 errors). The
# g5_skeleton_20261112_210500 copy already contains G5's OB_Main — usable
# only with --rename-ob (see attempt_03: renamed OB still fails compile in a
# skeleton that already owns a program-cycle OB).
DEFAULT_SKELETON = REPO / "tmp_validate" / "skeleton_canvas_20261112" / "proj"
BUSY_G5_SKELETON = REPO / "tmp_validate" / "g5_skeleton_20261112_210500" / "proj"
CHAIN_SCRIPT = REPO / "scripts" / "skeleton_delivery_v2.py"
JOB_ID = "job_processos_real_skel"


def _attach_lad_ob(manifest: Any, ws: Path, profile: Any) -> Any:
    """Render the OB as LAD XML (Name=Main, Number=1, ProgramCycle) and append
    it to the manifest as the last import (import-xml Override path).

    Pattern proven on real V19 by the v1 chain (gateway tia_delivery
    _render_ob_xml / _render_call_network, real OB1Main.xml precedent). The
    three FlgNet networks CALL each generated instance DB (EN-only; call
    parameters take defaults — full parameter wiring lives in the SCL OB for
    fresh-project delivery; recorded honestly in the driver output).
    """
    from xml.sax.saxutils import escape

    from gateway.app.services.plc.tia_delivery import _render_call_network, _render_multilingual
    from plc_engine.canonical import sha256_prefixed
    from plc_engine.process.artifact_manifest import ArtifactFile

    calls = [
        ("iFB_U_ASSEMBLY_UNIT", "FB_U_ASSEMBLY_UNIT"),
        ("iFB_EM_CLAMP_SEQ", "FB_EM_CLAMP_SEQ"),
        ("iFB_CM_CLAMP_CYL_DRV", "FB_CM_CLAMP_CYL_DRV"),
    ]

    def unit(uid: int, comment_uid: int, db: str, fb: str) -> str:
        return (
            f'      <SW.Blocks.CompileUnit ID="{uid}" CompositionName="CompileUnits">\n'
            "        <AttributeList>\n"
            f"          {_render_call_network(db, fb)}\n"
            "          <ProgrammingLanguage>LAD</ProgrammingLanguage>\n"
            "        </AttributeList>\n"
            "        <ObjectList>\n"
            f"{_render_multilingual(comment_uid, 'Comment', '')}\n"
            "        </ObjectList>\n"
            "      </SW.Blocks.CompileUnit>\n"
        )

    # SimaticML IDs must be document-unique: each multilingual text occupies
    # the given ID and ID+1 (MultilingualText + Item), each CompileUnit one.
    # Allocate 3 slots per unit to keep them disjoint (real-machine error:
    # "Duplicate Simatic ML ID '7'").
    units = "".join(unit(5 + i * 3, 6 + i * 3, db, fb) for i, (db, fb) in enumerate(calls))
    xml = (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        "<Document>\n"
        '  <Engineering version="V19" />\n'
        "  <DocumentInfo>\n"
        "    <Created>2026-11-15T00:00:00Z</Created>\n"
        "    <ExportSetting>WithDefaults</ExportSetting>\n"
        "  </DocumentInfo>\n"
        '  <SW.Blocks.OB ID="0">\n'
        "    <AttributeList>\n"
        "      <AutoNumber>false</AutoNumber>\n"
        "      <HeaderAuthor />\n"
        "      <HeaderFamily />\n"
        "      <HeaderName />\n"
        "      <HeaderVersion>0.1</HeaderVersion>\n"
        '      <Interface><Sections xmlns="http://www.siemens.com/automation/Openness/SW/Interface/v5">\n'
        '  <Section Name="Temp" />\n'
        '  <Section Name="Constant" />\n'
        "</Sections></Interface>\n"
        "      <IsIECCheckEnabled>false</IsIECCheckEnabled>\n"
        "      <MemoryLayout>Optimized</MemoryLayout>\n"
        "      <Name>Main</Name>\n"
        "      <Namespace />\n"
        "      <Number>1</Number>\n"
        "      <ProgrammingLanguage>LAD</ProgrammingLanguage>\n"
        "      <SecondaryType>ProgramCycle</SecondaryType>\n"
        "      <SetENOAutomatically>false</SetENOAutomatically>\n"
        "    </AttributeList>\n"
        "    <ObjectList>\n"
        f"{_render_multilingual(1, 'Comment', '')}\n"
        f"{units}"
        f"{_render_multilingual(20, 'Title', 'processos clamp cycle (LAD call shell)')}\n"
        "    </ObjectList>\n"
        "  </SW.Blocks.OB>\n"
        "</Document>\n"
    )
    src = ws / "sources"
    src.mkdir(parents=True, exist_ok=True)
    xml_path = src / "OB_Main.xml"
    xml_path.write_text(xml, encoding="utf-8")
    manifest.files.append(ArtifactFile(
        path=str(xml_path), sha256=sha256_prefixed(xml), role="OB",
        content=xml, source_ids=[], tia_block="Main",
    ))
    manifest.import_order.append(str(xml_path))
    manifest.sha256 = manifest.compute_sha256()
    print(f"[skeleton] OB attached as LAD XML (import-xml Override): {xml_path}")
    return manifest


def main() -> int:
    import argparse

    from datetime import datetime

    ap = argparse.ArgumentParser()
    ap.add_argument("--skeleton", default=str(DEFAULT_SKELETON),
                    help="skeleton project dir (default: pristine canvas baseline)")
    ap.add_argument("--ob-variant", choices=["wired", "minimal", "empty"], default="wired",
                    help="wired=full generated OB; minimal=parameterless calls; empty=no body at all")
    ap.add_argument("--ob-mode", choices=["scl", "ladxml"], default="scl",
                    help="scl=ExternalSources SCL OB (fails on this build: any SCL OB lands "
                         "inconsistent, even empty); ladxml=LAD OB via import-xml Override with "
                         "FlgNet CALL networks (v1 real-machine proven pattern)")
    ap.add_argument("--rename-ob", action="store_true",
                    help="rename OB_Main -> OB_AF_Main (busy skeleton with existing OB_Main only; "
                         "attempt_03 evidence shows renamed OB still fails compile there)")
    ap.add_argument("--ob-name", default="",
                    help="explicit OB block name override (e.g. 'Main' to overwrite the TIA "
                         "default main OB in the pristine canvas skeleton — ExternalSources "
                         "generate overwrites same-name blocks; our OB owns the cycle task)")
    args = ap.parse_args()
    skeleton_dir = Path(args.skeleton)

    from processos.backends import lower
    from processos.codegen import generate
    from processos.contract import clamp_contract
    from processos.frameworks import register_hr001_af_v19
    from processos.native.delivery import build_manifest

    if not (skeleton_dir / "CanvasE2E.ap19").is_file():
        print(f"[skeleton] missing skeleton project dir: {skeleton_dir}")
        return 2

    ts = datetime.now().strftime("%Y%m%d_%H%M%S")
    ws = REPO / "tmp_validate" / ("processos_real_skel_" + ts)
    proj_copy = ws / "proj"
    shutil.copytree(skeleton_dir, proj_copy)
    ap19 = proj_copy / "CanvasE2E.ap19"
    print(f"[skeleton] copy: {skeleton_dir} -> {proj_copy}")

    profile = register_hr001_af_v19()
    contract = clamp_contract()
    project = lower(contract, profile)
    gen = generate(project, profile)
    # Scope decision (precedent: evidence/v2/real/attempt_03 ob_renamed_import):
    # the busy G5 skeleton already contains its own OB_Main; ExternalSources
    # generation fails on an existing target name. The platform keeps the
    # semantic name OB_Main for fresh projects — this rename applies ONLY to
    # this busy-skeleton import path and is recorded in the receipt lineage.
    import dataclasses
    use_lad_ob = args.ob_mode == "ladxml"
    if use_lad_ob:
        # LAD OB via import-xml Override replaces the default Main (OB1) exactly;
        # the SCL OB file is dropped from this import set entirely.
        ob_out = ""
    elif args.ob_name:
        ob_out = args.ob_name + ".scl"
    elif args.rename_ob:
        ob_out = "OB_AF_Main.scl"
    else:
        ob_out = "OB_Main.scl"
    ob_decl = f'ORGANIZATION_BLOCK "{ob_out[:-4]}"'
    renamed_files = {}
    for fname, text in gen.files.items():
        if fname == "OB_Main.scl" and use_lad_ob:
            continue  # OB ships as LAD XML below (import-xml Override path)
        if fname == "OB_Main.scl":
            out = text.replace('ORGANIZATION_BLOCK "OB_Main"', ob_decl)
            if args.ob_variant == "minimal":
                # Debug bisect variant (recorded): parameterless calls, no
                # VAR_TEMP, no cross-instance access — isolates whether the
                # compile error comes from the wiring constructs.
                out = (
                    ob_decl + "\n"
                    "BEGIN\n"
                    '    "iFB_U_ASSEMBLY_UNIT"();\n'
                    '    "iFB_EM_CLAMP_SEQ"();\n'
                    '    "iFB_CM_CLAMP_CYL_DRV"();\n'
                    "END_ORGANIZATION_BLOCK\n"
                )
            elif args.ob_variant == "empty":
                # Debug bisect variant (recorded): truly empty body — if this
                # still fails, the error is in OB1 generation itself (header/
                # numbering), not in any call.
                out = ob_decl + "\nBEGIN\nEND_ORGANIZATION_BLOCK\n"
            renamed_files[ob_out] = out
        else:
            renamed_files[fname] = text
    gen = dataclasses.replace(gen, files=renamed_files)
    if ob_out != "OB_Main.scl":
        print(f"[skeleton] OB_Main -> {ob_out[:-4]} (recorded scope decision: {args.ob_name or 'busy-skeleton rename'})")
    manifest = build_manifest(gen, project, profile, ws)
    if use_lad_ob:
        manifest = _attach_lad_ob(manifest, ws, profile)
    manifest_path = ws / "manifest.json"
    import json as _json
    manifest_path.write_text(_json.dumps(manifest.to_dict(), ensure_ascii=False), encoding="utf-8")
    print(f"[skeleton] manifest: {len(manifest.import_order)} files, sha={manifest.sha256}")

    receipt_path = ws / "chain_receipt.json"
    evidence_dir = ws / "evidence"
    argv = [
        str(CHAIN_SCRIPT),
        "--project", str(ap19),
        "--manifest-json", str(manifest_path),
        "--workspace-dir", str(ws),
        "--project-id", "PRJ_CLAMP_REAL",
        "--job-id", JOB_ID,
        "--output", str(receipt_path),
        "--evidence-dir", str(evidence_dir),
        "--real",
    ]
    print("[skeleton] running real chain in-process (runpy, no shell)")
    exit_code = 0
    saved_argv = sys.argv
    sys.argv = argv
    try:
        runpy.run_path(str(CHAIN_SCRIPT), run_name="__main__")
    except SystemExit as exc:  # argparse/chain scripts exit via SystemExit
        exit_code = int(exc.code or 0)
    finally:
        sys.argv = saved_argv
    print(f"[skeleton] chain exit={exit_code}")

    if receipt_path.is_file():
        import json
        data = json.loads(receipt_path.read_text(encoding="utf-8"))
        print(f"[skeleton] mode={data.get('mode')} evidence={data.get('evidence_level')}")
        print(f"[skeleton] receipt: {receipt_path}")
    return exit_code


if __name__ == "__main__":
    raise SystemExit(main())
